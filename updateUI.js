const fs = require('fs');

function updateComponent(path, replaces) {
  let content = fs.readFileSync(path, 'utf-8');
  for (const r of replaces) {
    content = content.replace(r.from, r.to);
  }
  fs.writeFileSync(path, content, 'utf-8');
}

updateComponent('components/hero/HeroContent.tsx', [
  {
    from: '{headline}',
    to: '<span dangerouslySetInnerHTML={{ __html: headline }} />'
  },
  {
    from: '{description}',
    to: '<span dangerouslySetInnerHTML={{ __html: description }} />'
  },
  {
    from: '{indicator}',
    to: '<span dangerouslySetInnerHTML={{ __html: indicator }} />'
  }
]);

